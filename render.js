/* Success AI — in-browser film renderer (FFmpeg compiled to WebAssembly, vendored in /vendor).
 * Joins scene clips into one MP4, mixes clip sound + narration + music, and embeds subtitles.
 * Everything runs on the user's device: no render server, no upload of the final film.
 */
(() => {
  "use strict";
  const abs = p => new URL(p, location.href).href;
  let ffmpeg = null;
  let loading = null;
  let logSink = null;
  let progressSink = null;

  async function load(onStatus) {
    if (ffmpeg) return ffmpeg;
    if (!loading) {
      loading = (async () => {
        onStatus?.("Loading the video engine (about 30 MB, first time only)…");
        const { FFmpeg } = await import(abs("ffmpeg-index.js"));
        const ff = new FFmpeg();
        ff.on("log", ({ message }) => logSink && logSink(message));
        ff.on("progress", ({ progress }) => progressSink && progressSink(Math.max(0, Math.min(1, progress))));
        // Prefer the self-hosted engine; fall back to the public CDN copy of the exact same version
        // (useful when the 31 MB .wasm wasn't uploaded, e.g. GitHub's web uploader caps files at 25 MB).
        const local = await fetch(abs("ffmpeg-core.wasm"), { method: "HEAD" }).then(r => r.ok).catch(() => false);
        const base = local ? abs("./") : "https://cdn.jsdelivr.net/npm/@ffmpeg/core@0.12.10/dist/esm/";
        await ff.load({ coreURL: base + "ffmpeg-core.js", wasmURL: base + "ffmpeg-core.wasm" });
        ffmpeg = ff;
        return ff;
      })().catch(e => {
        loading = null;
        throw new Error("Couldn't start the video engine in this browser: " + (e?.message || e));
      });
    }
    return loading;
  }

  /** Run ffmpeg, returning { code, log }. */
  async function run(args, onProgress) {
    const lines = [];
    logSink = m => lines.push(m);
    progressSink = onProgress || null;
    let code;
    try {
      code = await ffmpeg.exec(args);
    } finally {
      logSink = null;
      progressSink = null;
    }
    return { code, log: lines.join("\n") };
  }

  async function probe(name) {
    const { log } = await run(["-hide_banner", "-i", name]);
    const d = log.match(/Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)/);
    const v = log.match(/Video:\s*(\w+)[^\n]*?,\s*(\d{2,5})x(\d{2,5})/);
    const fps = log.match(/(\d+(?:\.\d+)?)\s*fps/);
    return {
      duration: d ? Number(d[1]) * 3600 + Number(d[2]) * 60 + Number(d[3]) : 0,
      vcodec: v?.[1] || "",
      width: v ? Number(v[2]) : 0,
      height: v ? Number(v[3]) : 0,
      fps: fps ? Number(fps[1]) : 0,
      hasAudio: /Audio:/.test(log)
    };
  }

  const bytes = async b => new Uint8Array(await b.arrayBuffer());
  const srtTime = t => {
    const ms = Math.max(0, Math.round(t * 1000));
    const p = (n, l = 2) => String(n).padStart(l, "0");
    return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
  };
  const even = n => Math.max(2, Math.round(n / 2) * 2);

  /**
   * Render a film.
   * @param {object} o
   *   clips: [{ blob, inPoint?, outPoint?, narration?: Blob, subtitle?: string }]
   *   music: { blob, volume? } | null
   *   keepClipAudio: boolean (default true)  — keeps sound generated by the video model
   *   onStatus(text), onProgress(0..1)
   * @returns {Promise<{ blob: Blob, duration: number, srt: string }>}
   */
  async function film(o) {
    const status = o.onStatus || (() => {});
    const overall = o.onProgress || (() => {});
    if (!o.clips?.length) throw new Error("No clips to render.");
    await load(status);
    const files = [];
    const write = async (name, blob) => {
      await ffmpeg.writeFile(name, await bytes(blob));
      files.push(name);
    };
    try {
      // 1. Load clips and inspect them.
      status("Preparing clips…");
      const info = [];
      for (let i = 0; i < o.clips.length; i++) {
        await write(`c${i}.mp4`, o.clips[i].blob);
        const p = await probe(`c${i}.mp4`);
        if (!p.duration || !p.width) throw new Error(`Clip ${i + 1} isn't a readable video.`);
        const inP = Math.max(0, Math.min(Number(o.clips[i].inPoint) || 0, p.duration - 0.2));
        const outP = Math.min(p.duration, Number(o.clips[i].outPoint) || p.duration);
        info.push({ ...p, inP, len: Math.max(0.2, outP - inP), trimmed: inP > 0 || outP < p.duration - 0.05 });
        overall(0.05 + (0.1 * (i + 1)) / o.clips.length);
      }

      // 2. Normalize every clip to the same size/fps/codec (robust concat; also applies trims exactly).
      const W = even(info[0].width);
      const H = even(info[0].height);
      const same = info.every(c => c.vcodec === "h264" && c.width === info[0].width && c.height === info[0].height && Math.abs(c.fps - info[0].fps) < 0.01 && !c.trimmed);
      const parts = [];
      for (let i = 0; i < info.length; i++) {
        const c = info[i];
        const name = `n${i}.mp4`;
        status(same ? `Joining clip ${i + 1} of ${info.length}…` : `Converting clip ${i + 1} of ${info.length}…`);
        const base = ["-hide_banner", "-y", "-ss", String(c.inP), "-i", `c${i}.mp4`, "-t", c.len.toFixed(3), "-an"];
        const args = same
          ? [...base, "-c:v", "copy", name]
          : [...base, "-vf", `scale=${W}:${H}:force_original_aspect_ratio=decrease,pad=${W}:${H}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps=24,format=yuv420p`, "-c:v", "libx264", "-preset", "ultrafast", "-crf", "21", name];
        const r = await run(args, p => overall(0.15 + (0.45 * (i + p)) / info.length));
        if (r.code !== 0) throw new Error(`Couldn't process clip ${i + 1}: ` + r.log.split("\n").slice(-3).join(" "));
        files.push(name);
        parts.push(name);
      }
      await ffmpeg.writeFile("list.txt", parts.map(p => `file '${p}'`).join("\n"));
      files.push("list.txt");
      status("Joining scenes…");
      let r = await run(["-hide_banner", "-y", "-f", "concat", "-safe", "0", "-i", "list.txt", "-c", "copy", "joined.mp4"]);
      if (r.code !== 0) throw new Error("Couldn't join the clips: " + r.log.split("\n").slice(-3).join(" "));
      files.push("joined.mp4");
      const total = (await probe("joined.mp4")).duration || info.reduce((n, c) => n + c.len, 0);
      overall(0.65);

      // 3. Build the soundtrack: clip sound (if any), narration at each scene's start, music bed.
      const inputs = [];
      const filters = [];
      const labels = [];
      let starts = 0;
      const sceneStart = [];
      info.forEach(c => {
        sceneStart.push(starts);
        starts += c.len;
      });

      const keep = o.keepClipAudio !== false && info.some(c => c.hasAudio);
      if (keep) {
        status("Extracting scene sound…");
        for (let i = 0; i < info.length; i++) {
          const c = info[i];
          const args = c.hasAudio
            ? ["-hide_banner", "-y", "-ss", String(c.inP), "-i", `c${i}.mp4`, "-t", c.len.toFixed(3), "-vn", "-ac", "2", "-ar", "44100", "-af", `apad=whole_dur=${c.len.toFixed(3)}`, `a${i}.wav`]
            : ["-hide_banner", "-y", "-f", "lavfi", "-i", "anullsrc=r=44100:cl=stereo", "-t", c.len.toFixed(3), `a${i}.wav`];
          r = await run(args);
          if (r.code !== 0) throw new Error("Couldn't extract clip sound: " + r.log.split("\n").slice(-2).join(" "));
          files.push(`a${i}.wav`);
        }
        info.forEach((_, i) => inputs.push("-i", `a${i}.wav`));
        filters.push(info.map((_, i) => `[${i + 1}:a]`).join("") + `concat=n=${info.length}:v=0:a=1,volume=${o.clipVolume ?? 1}[clipa]`);
        labels.push("[clipa]");
      }
      let idx = 1 + (keep ? info.length : 0);
      for (let i = 0; i < o.clips.length; i++) {
        if (!o.clips[i].narration) continue;
        await write(`v${i}.audio`, o.clips[i].narration);
        inputs.push("-i", `v${i}.audio`);
        const ms = Math.round((sceneStart[i] + 0.3) * 1000);
        filters.push(`[${idx}:a]aformat=sample_rates=44100:channel_layouts=stereo,adelay=${ms}|${ms},volume=${o.narrationVolume ?? 1.6}[nar${i}]`);
        labels.push(`[nar${i}]`);
        idx++;
      }
      if (o.music?.blob) {
        await write("music.audio", o.music.blob);
        inputs.push("-stream_loop", "-1", "-i", "music.audio");
        const fadeStart = Math.max(0, total - 2.5).toFixed(2);
        filters.push(`[${idx}:a]aformat=sample_rates=44100:channel_layouts=stereo,atrim=0:${total.toFixed(2)},volume=${o.music.volume ?? (labels.length ? 0.28 : 0.9)},afade=t=in:d=1.5,afade=t=out:st=${fadeStart}:d=2.5[mus]`);
        labels.push("[mus]");
        idx++;
      }

      // 4. Subtitles (soft subtitle track, works in most players).
      let srt = "";
      let n = 1;
      o.clips.forEach((c, i) => {
        if (c.subtitle?.trim()) srt += `${n++}\n${srtTime(sceneStart[i])} --> ${srtTime(sceneStart[i] + info[i].len)}\n${c.subtitle.trim()}\n\n`;
      });

      status("Mixing sound and writing your film…");
      const args = ["-hide_banner", "-y", "-i", "joined.mp4", ...inputs];
      if (srt) {
        await ffmpeg.writeFile("subs.srt", srt);
        files.push("subs.srt");
        args.push("-i", "subs.srt");
      }
      if (labels.length) {
        const mix = labels.length === 1 ? `${labels[0]}anull[aout]` : `${labels.join("")}amix=inputs=${labels.length}:duration=longest:normalize=0,alimiter=limit=0.95[aout]`;
        args.push("-filter_complex", [...filters, mix].join(";"), "-map", "0:v", "-map", "[aout]", "-c:a", "aac", "-b:a", "192k");
      } else args.push("-map", "0:v");
      if (srt) args.push("-map", `${idx}:s`, "-c:s", "mov_text", "-metadata:s:s:0", "language=eng");
      args.push("-c:v", "copy", "-t", total.toFixed(3), "-movflags", "+faststart", "film.mp4");
      r = await run(args, p => overall(0.7 + 0.28 * p));
      if (r.code !== 0) throw new Error("Couldn't write the final film: " + r.log.split("\n").slice(-4).join(" "));
      files.push("film.mp4");
      const data = await ffmpeg.readFile("film.mp4");
      overall(1);
      status("Done.");
      return { blob: new Blob([data.buffer], { type: "video/mp4" }), duration: total, srt };
    } finally {
      for (const f of files) {
        try {
          await ffmpeg.deleteFile(f);
        } catch {
          /* already gone */
        }
      }
    }
  }

  SA.render = { load, film, probe: async blob => { await load(); await ffmpeg.writeFile("p.mp4", await bytes(blob)); const r = await probe("p.mp4"); await ffmpeg.deleteFile("p.mp4"); return r; } };
})();
